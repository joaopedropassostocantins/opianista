import type { Language } from "../types/content.ts";
export function ProjectBrief(lang: Language): string {
  const cards = lang === "pt" ? [
    ["01", "A pergunta", "Como distinguir o evento real do registro criado por quem controla o sistema?"],
    ["02", "O método", "Testar hipóteses preregistradas com controles, poder e explicações rivais."],
    ["03", "A exigência", "Fontes externas, integridade demonstrável e revisão independente."],
    ["04", "O limite", "Sem dados e testes suficientes, não concluir fraude nem ausência de fraude."]
  ] : [
    ["01", "The question", "How can we distinguish a real event from a record generated by its operator?"],
    ["02", "The method", "Test preregistered hypotheses with controls, power and rival explanations."],
    ["03", "The requirement", "External sources, verifiable integrity and independent review."],
    ["04", "The limit", "Without adequate data and tests, conclude neither fraud nor its absence."]
  ];
  return '<section class="section" id="tese" aria-labelledby="tese-title"><div class="container">' +
    '<div class="section-top"><p class="eyebrow">' + (lang === "pt" ? "01 / PONTO DE PARTIDA" : "01 / STARTING POINT") + '</p>' +
    '<h2 id="tese-title">' + (lang === "pt" ? "O registro não é o evento." : "A record is not the event.") + '</h2>' +
    '<p>' + (lang === "pt" ? "A integridade de um arquivo permite afirmar que ele não foi alterado desde determinado estado; não demonstra, isoladamente, a veracidade de cada fato que descreve." : "File integrity can show that a file has not changed since a particular state; by itself it cannot establish the truth of every event described.") + '</p></div>' +
    '<div class="brief-grid">' + cards.map(c => '<article class="brief-card"><span class="card-index">' + c[0] + '</span><h3>' + c[1] + '</h3><p>' + c[2] + '</p></article>').join("") + '</div></div></section>';
}
